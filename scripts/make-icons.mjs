// Regenerates the committed icon assets:
//   src/icons/icon-{16,32,48,128}.png  from src/icons/icon.svg (via sharp)
//   src/shared/icons.js                the Lucide icons the commands use
// Run with `npm run icons` after changing the logo or a command's icon.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';
import { COMMANDS, UI_ICONS } from '../src/shared/commands.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const logo = await readFile(path.join(root, 'src/icons/icon.svg'));
for (const size of [16, 32, 48, 128]) {
  await sharp(logo, { density: 384 }).resize(size, size).png().toFile(path.join(root, `src/icons/icon-${size}.png`));
}

const names = [...new Set([...COMMANDS.map((c) => c.icon), ...UI_ICONS])].sort();
const icons = {};
for (const name of names) {
  const svg = await readFile(path.join(root, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8')
    .catch(() => { throw new Error(`Unknown Lucide icon: ${name}`); });
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  icons[name] = [...body.matchAll(/<(\w+)\s+([^>]*?)\s*\/>/g)].map(([, tag, attrs]) =>
    [tag, Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))]);
  if (!icons[name].length) throw new Error(`Could not parse icon: ${name}`);
}

const out = `// Generated by scripts/make-icons.mjs from lucide-static (ISC License). Do not edit.
const ICONS = ${JSON.stringify(icons)};
const NS = 'http://www.w3.org/2000/svg';

export const ICON_NAMES = Object.keys(ICONS);

export function icon(name, size = 16) {
  const svg = document.createElementNS(NS, 'svg');
  const attrs = { width: size, height: size, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor',
    'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true' };
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, v);
  for (const [tag, props] of ICONS[name] || []) {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(props)) el.setAttribute(k, v);
    svg.append(el);
  }
  return svg;
}
`;
await writeFile(path.join(root, 'src/shared/icons.js'), out);
console.log(`icons: ${names.length} glyphs, 4 PNG sizes`);
